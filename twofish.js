function gfMult(a,b,p){
  let bb=b>>>0,result=0; a&=255;
  for(let i=0;i<8;i++){
    if(a&1)result^=bb;
    a>>>=1;
    bb=((bb<<1)^((bb>>>7)?p:0))>>>0;
  }
  return result&255;
}
